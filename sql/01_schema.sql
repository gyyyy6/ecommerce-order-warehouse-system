-- ============================================================
-- 01_schema.sql
-- 作用：由 db_owner 执行，重建核心表、触发器和权限。
-- 特点：幂等（先 DROP 再 CREATE）；不包含 demo_drop_me。
-- 运行：
--   psql -h 127.0.0.1 -U db_owner -d course_db -f sql/01_schema.sql
-- ============================================================

\set ON_ERROR_STOP on

BEGIN;

-- 按依赖倒序删除，保证可重复执行
DROP TABLE IF EXISTS access_log, shipment, order_item, orders,
                     product_category, product, category, customer CASCADE;

-- 通用 updated_at 触发器函数
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

-- 1. 客户
CREATE TABLE customer (
    customer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(80)  NOT NULL,
    email         VARCHAR(160) NOT NULL,
    phone         VARCHAR(32),
    address       VARCHAR(255),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT ck_customer_name_not_blank CHECK (length(btrim(customer_name)) > 0),
    CONSTRAINT ck_customer_email_not_blank CHECK (position('@' IN email) > 1)
);

-- 2. 商品分类
CREATE TABLE category (
    category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(80) NOT NULL,
    description   TEXT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_category_name UNIQUE (category_name),
    CONSTRAINT ck_category_name_not_blank CHECK (length(btrim(category_name)) > 0)
);

-- 3. 商品
CREATE TABLE product (
    product_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku          VARCHAR(64)  NOT NULL,
    product_name VARCHAR(160) NOT NULL,
    unit_price   NUMERIC(12,2) NOT NULL,
    stock        INTEGER      NOT NULL DEFAULT 0,
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_price_nonnegative CHECK (unit_price >= 0),
    CONSTRAINT ck_product_stock_nonnegative CHECK (stock >= 0),
    CONSTRAINT ck_product_name_not_blank CHECK (length(btrim(product_name)) > 0)
);

-- 4. 商品—分类 N-M 联系
CREATE TABLE product_category (
    product_id  BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    CONSTRAINT pk_product_category PRIMARY KEY (product_id, category_id),
    CONSTRAINT fk_product_category_product
        FOREIGN KEY (product_id) REFERENCES product(product_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_product_category_category
        FOREIGN KEY (category_id) REFERENCES category(category_id)
        ON DELETE RESTRICT
);

-- 5. 订单
CREATE TABLE orders (
    order_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      BIGINT NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    shipping_address VARCHAR(255) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    cancelled_at     TIMESTAMPTZ,
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customer(customer_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_orders_status
        CHECK (status IN ('PENDING', 'PAID', 'SHIPPED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_cancelled_at
        CHECK (status <> 'CANCELLED' OR cancelled_at IS NOT NULL),
    CONSTRAINT ck_orders_address_not_blank
        CHECK (length(btrim(shipping_address)) > 0)
);

-- 6. 订单明细
-- 主键仍是 (order_id, product_id)
-- order_item_id 只是唯一代理列，供 DELETE /api/order-items/<id> 使用
CREATE TABLE order_item (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    order_id      BIGINT NOT NULL,
    product_id    BIGINT NOT NULL,
    quantity      INTEGER NOT NULL,
    unit_price    NUMERIC(12,2) NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, product_id),
    CONSTRAINT uq_order_item_id UNIQUE (order_item_id),
    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id) REFERENCES orders(order_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_order_item_product
        FOREIGN KEY (product_id) REFERENCES product(product_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_order_item_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_item_price_nonnegative CHECK (unit_price >= 0)
);

-- 7. 物流单：order_id 唯一，表达 1-1
CREATE TABLE shipment (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id    BIGINT NOT NULL,
    carrier     VARCHAR(80) NOT NULL,
    tracking_no VARCHAR(80) NOT NULL,
    status      VARCHAR(20) NOT NULL DEFAULT 'CREATED',
    shipped_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_shipment_order UNIQUE (order_id),
    CONSTRAINT uq_shipment_tracking_no UNIQUE (tracking_no),
    CONSTRAINT fk_shipment_order
        FOREIGN KEY (order_id) REFERENCES orders(order_id)
        ON DELETE CASCADE,
    CONSTRAINT ck_shipment_status
        CHECK (status IN ('CREATED', 'IN_TRANSIT', 'DELIVERED', 'RETURNED')),
    CONSTRAINT ck_shipment_carrier_not_blank
        CHECK (length(btrim(carrier)) > 0),
    CONSTRAINT ck_shipment_tracking_not_blank
        CHECK (length(btrim(tracking_no)) > 0)
);

-- 8. 访问日志（运维表，不是业务实体）
CREATE TABLE access_log (
    log_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    method      VARCHAR(10) NOT NULL,
    path        VARCHAR(255) NOT NULL,
    status_code INTEGER NOT NULL,
    duration_ms NUMERIC(10,2) NOT NULL,
    client_ip   VARCHAR(64),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_access_log_status CHECK (status_code BETWEEN 100 AND 599),
    CONSTRAINT ck_access_log_duration CHECK (duration_ms >= 0)
);

-- updated_at 触发器
DROP TRIGGER IF EXISTS trg_customer_updated_at ON customer;
CREATE TRIGGER trg_customer_updated_at
BEFORE UPDATE ON customer
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_product_updated_at ON product;
CREATE TRIGGER trg_product_updated_at
BEFORE UPDATE ON product
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_orders_updated_at ON orders;
CREATE TRIGGER trg_orders_updated_at
BEFORE UPDATE ON orders
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_shipment_updated_at ON shipment;
CREATE TRIGGER trg_shipment_updated_at
BEFORE UPDATE ON shipment
FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- 表注释
COMMENT ON TABLE customer IS '客户';
COMMENT ON TABLE category IS '商品分类';
COMMENT ON TABLE product IS '商品';
COMMENT ON TABLE product_category IS '商品—分类 N-M 联系';
COMMENT ON TABLE orders IS '订单';
COMMENT ON TABLE order_item IS '订单明细；主键 (order_id, product_id)';
COMMENT ON TABLE shipment IS '物流单；order_id 唯一，表达 1-1';
COMMENT ON TABLE access_log IS 'Flask 访问日志，运维表';

-- 运行时账号只给 DML 与序列权限，不给 DDL
GRANT USAGE ON SCHEMA public TO app_rw;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO app_rw;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO app_rw;
REVOKE CREATE ON SCHEMA public FROM app_rw;

-- 以后由 db_owner 新建的表/序列，自动授予 app_rw 对应权限
ALTER DEFAULT PRIVILEGES FOR ROLE db_owner IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO app_rw;
ALTER DEFAULT PRIVILEGES FOR ROLE db_owner IN SCHEMA public
    GRANT USAGE, SELECT ON SEQUENCES TO app_rw;

COMMIT;