\set ON_ERROR_STOP on
\echo '=== 1. 创建 demo_drop_me ==='

BEGIN;

DROP TABLE IF EXISTS demo_drop_me;

CREATE TABLE demo_drop_me (
    demo_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note      VARCHAR(120) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

\echo '=== 2. 插入演示数据 ==='
INSERT INTO demo_drop_me (note) VALUES ('drop table demo'), ('course project');
SELECT * FROM demo_drop_me ORDER BY demo_id;

\echo '=== 3. 删除 demo_drop_me ==='
DROP TABLE demo_drop_me;

COMMIT;

